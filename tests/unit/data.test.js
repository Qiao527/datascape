import { createHash } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import { beamHeight, slantForGround } from '../../src/storm/beam.js';
import { readStorm } from './load.js';

const { meta, raw, compressed, data } = readStorm();
const { box, encoding } = meta;
const keepCode = Math.round((encoding.keep - encoding.min) / encoding.step) + 1;

describe('storm.bin', () => {
  it('is the scan regenerated by scripts/storm/generate_storm.py', () => {
    // Recorded after a byte-identical rerun of the generator on
    // KDDC20130519_000455_V06.gz (see docs/storm-chamber.md).
    expect(createHash('sha256').update(compressed).digest('hex')).toBe('78c17d379f7f5bb78958616a5a646fc0ce402dd4e6de4f4769eb61baa524d3ba');
    expect(createHash('sha256').update(raw).digest('hex').slice(0, 16)).toBe('6ee9e26aed4a7736');
  });

  it('lays out volume, low and upper back to back, with the sizes the manifest declares', () => {
    const { volume, low, upper } = meta.layout;
    expect(volume).toEqual({ offset: 0, length: box.nx * box.ny * box.nz });
    expect(low).toEqual({ offset: volume.length, length: meta.polar.low.naz * meta.polar.low.ngates });
    expect(upper).toEqual({
      offset: low.offset + low.length,
      length: meta.polar.upper.layers * meta.polar.upper.naz * meta.polar.upper.ngates
    });
    expect(raw.length).toBe(upper.offset + upper.length);
  });

  it('describes the box the About panel promises: 80 x 80 km, 20 km tall, 0.5 km cells', () => {
    expect(box.cell).toBe(0.5);
    expect((box.nx - 1) * box.cell).toBe(80);
    expect((box.ny - 1) * box.cell).toBe(80);
    expect(box.z0 + (box.nz - 1) * box.cell).toBe(20);
  });

  it('keeps only echoes of 10 dBZ and up', () => {
    for (const array of [data.volume, data.low, data.upper]) {
      let min = 256;
      for (const code of array) if (code && code < min) min = code;
      expect(min).toBeGreaterThanOrEqual(keepCode);
      expect(data.dbz(min)).toBeGreaterThanOrEqual(encoding.keep);
    }
    expect(data.dbz(0)).toBeNull();
    expect(data.dbz(1)).toBe(encoding.min);
  });

  it('leaves the upper sweeps empty beyond the range each one measured', () => {
    const { naz, ngates, gate } = meta.polar.upper;
    meta.sweeps.slice(1).forEach((sweep, layer) => {
      const first = Math.ceil(sweep.rmax / gate);
      for (let a = 0; a < naz; a += 1) {
        for (let g = first; g < ngates; g += 1) expect(data.upper[layer * naz * ngates + a * ngates + g]).toBe(0);
      }
      expect(data.sweepCode(layer + 1, sweep.rmax + 1, 45)).toBe(-1);
    });
  });

  it('leaves the box empty below the radar site', () => {
    const below = Math.ceil((meta.radar.siteKm - box.z0) / box.cell); // voxel centres under the site
    for (let n = 0; n < box.nx * box.ny * below; n += 1) expect(data.volume[n]).toBe(0);
  });
});

describe('lookups', () => {
  it('index the volume as [z][north][east]', () => {
    const i = 37;
    const j = 101;
    const k = 12;
    const x = box.x0 + i * box.cell;
    const y = box.y0 + j * box.cell;
    const z = box.z0 + k * box.cell;
    expect(data.volumeCode(x, y, z)).toBe(data.volume[i + box.nx * (j + box.ny * k)]);
    expect(data.volumeCode(box.x0 - 5, y, z)).toBe(-1);
    expect(data.volumeCode(x, y, 30)).toBe(-1);
  });

  it('wrap azimuth and bin range like the generator', () => {
    const { ngates, gate } = meta.polar.low;
    expect(data.sweepCode(0, 60.1, -10)).toBe(data.sweepCode(0, 60.1, 350));
    expect(data.sweepCode(0, 60.1, 370)).toBe(data.sweepCode(0, 60.1, 10));
    // Range bin g covers [g, g + 1) x gate; azimuth bin a covers [a, a + 1) x 0.5 deg.
    expect(data.sweepCode(0, 60.1, 45.2)).toBe(data.low[90 * ngates + Math.floor(60.1 / gate)]);
  });

  it('find the strongest echo along every ray', () => {
    expect(data.rayPeaks).toHaveLength(meta.sweeps.length);
    expect(data.rayPeaks[0]).toHaveLength(meta.polar.low.naz);
    const { ngates } = meta.polar.low;
    let best = 0;
    for (let g = 0; g < ngates; g += 1) best = Math.max(best, data.low[200 * ngates + g]);
    expect(data.rayPeaks[0][200]).toBeCloseTo(data.dbz(best) ?? 0, 4); // stored as float32
  });

  it('summarise a horizontal slice', () => {
    const k = Math.round((5 - box.z0) / box.cell);
    let best = 0;
    let cells = 0;
    for (let n = 0; n < box.nx * box.ny; n += 1) {
      const code = data.volume[box.nx * box.ny * k + n];
      best = Math.max(best, code);
      if (code && data.dbz(code) >= 30 - 1e-9) cells += 1;
    }
    const stats = data.sliceStats(5);
    expect(stats.max).toBeCloseTo(data.dbz(best), 9);
    expect(stats.areaKm2).toBe(cells * box.cell ** 2);
  });
});

describe('gridded volume', () => {
  it('agrees with the sweeps it was built from, on the sweep surfaces', () => {
    for (const index of [2, 5, 8]) {
      const el = meta.sweeps[index].el;
      const diffs = [];
      let either = 0;
      for (let e = 10; e < 80; e += 1.3) {
        for (let n = 18; n < 90; n += 1.3) {
          const r = slantForGround(Math.hypot(e, n), el);
          const z = beamHeight(r, el) + meta.radar.antennaKm;
          if (z < 1.2 || z > 19.5) continue;
          const sweep = data.dbz(data.sweepCode(index, r, (Math.atan2(e, n) * 180) / Math.PI));
          const cell = data.dbz(data.volumeCode(e, n, z));
          if (sweep === null && cell === null) continue;
          either += 1;
          if (sweep !== null && cell !== null) diffs.push(Math.abs(sweep - cell));
        }
      }
      diffs.sort((a, b) => a - b);
      expect(diffs.length / either).toBeGreaterThan(0.85);
      expect(diffs[Math.floor(diffs.length / 2)]).toBeLessThan(2.5);
      expect(diffs[Math.floor(diffs.length * 0.9)]).toBeLessThan(6);
    }
  });
});
